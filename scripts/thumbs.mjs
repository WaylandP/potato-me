#!/usr/bin/env node
// Builds assets/thumbs/<group>/<key>.png (256 px) from assets/parts and writes
// src/assets.js, the static index of which parts exist. Run after adding or
// replacing part images. Needs Playwright (dev tool only, like render.mjs).
//
//   npm run assets

import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const manifest = JSON.parse(await readFile(root + 'assets/manifest.json', 'utf8'));
const THUMB = 256;

let chromium;
try {
  ({ chromium } = createRequire(import.meta.url)('playwright'));
} catch {
  console.error('Playwright is not installed. Run: npm i -D playwright && npx playwright install chromium');
  process.exit(1);
}

const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto('about:blank');
let n = 0;
for (const a of manifest.assets) {
  const png = await readFile(root + a.path);
  const dataUrl = 'data:image/png;base64,' + png.toString('base64');
  const out = await page.evaluate(
    ([src, size]) =>
      new Promise((resolve, reject) => {
        const img = new Image();
        img.onload = () => {
          const c = document.createElement('canvas');
          c.width = c.height = size;
          const ctx = c.getContext('2d');
          ctx.imageSmoothingQuality = 'high';
          ctx.drawImage(img, 0, 0, size, size);
          resolve(c.toDataURL('image/png'));
        };
        img.onerror = reject;
        img.src = src;
      }),
    [dataUrl, THUMB],
  );
  const dest = root + a.path.replace('assets/parts/', 'assets/thumbs/');
  await mkdir(dest.slice(0, dest.lastIndexOf('/')), { recursive: true });
  await writeFile(dest, Buffer.from(out.split(',')[1], 'base64'));
  n++;
}
await browser.close();

// Static index: { group: { key: placedBox } } so the app never has to fetch the manifest.
const index = {};
for (const a of manifest.assets) {
  (index[a.group] ||= {})[a.key] = a.placedBox;
}
const js = `// Generated by scripts/thumbs.mjs from assets/manifest.json. Do not edit by hand.
// Which part images exist, with the box each one occupies on the 1024 px canvas.

export const CANVAS = ${manifest.canvas.width};
export const LAYER_ORDER = ${JSON.stringify(manifest.layerOrder)};
export const NO_IMAGE = ${JSON.stringify(manifest.noImageRequired)};
export const PARTS = ${JSON.stringify(index, null, 2)};
`;
await writeFile(root + 'src/assets.js', js);
console.log(`wrote ${n} thumbnails and src/assets.js`);
